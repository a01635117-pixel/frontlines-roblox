// Rasterises upstream HUD icons (resources/images/*.svg, CC BY-SA 4.0) into
// raw RGBA bitmaps for EditableImage, since Roblox cannot draw SVG.
//
// Usage (once: `npm install` in tools/):
//   node tools/pack-icons.mjs [path/to/OpenFrontIO]
// Writes src/shared/Data/Icons.luau: { [name] = { size = n, rgba = base64 } }.

