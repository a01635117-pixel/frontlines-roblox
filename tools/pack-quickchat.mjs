// Writes src/shared/Data/QuickChat.luau from upstream resources/QuickChat.json
// and the English texts in resources/lang/en.json ("chat").
//   node tools/pack-quickchat.mjs [path/to/OpenFrontIO]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const upstream = process.argv[2] ?? process.env.OPENFRONT_DIR ?? path.resolve(here, "../../OpenFrontIO");
const phrases = JSON.parse(fs.readFileSync(path.join(upstream, "resources/QuickChat.json"), "utf8"));
const chat = JSON.parse(fs.readFileSync(path.join(upstream, "resources/lang/en.json"), "utf8")).chat;
// ChatModal.categories order.
const CATEGORIES = ["help", "attack", "defend", "greet", "misc", "warnings"];
const q = (s) => JSON.stringify(s);
const lines = CATEGORIES.map((c) => {
  const rows = (phrases[c] ?? []).map((p) => `\t\t\t{ key = ${q(p.key)}, requiresPlayer = ${p.requiresPlayer === true}, text = ${q(chat[c][p.key])} },`);
  return `\t{\n\t\tid = ${q(c)},\n\t\tname = ${q(chat.cat[c])},\n\t\tphrases = {\n${rows.join("\n")}\n\t\t},\n\t},`;
});
const out = `-- AUTO-GENERATED by tools/pack-quickchat.mjs from upstream OpenFrontIO
-- resources/QuickChat.json + resources/lang/en.json (chat). Do not edit.
return {
${lines.join("\n")}
}
`;
fs.writeFileSync(path.resolve(here, "../src/shared/Data/QuickChat.luau"), out);
console.log(`${CATEGORIES.length} categories`);
