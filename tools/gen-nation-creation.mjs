// Generates src/server/Core/NationCreation.luau from upstream
// src/core/game/NationCreation.ts (logic hand-ported below; the name
// templates / nouns / plural tables are copied verbatim from the source).
//   node tools/gen-nation-creation.mjs [path/to/OpenFrontIO]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const upstream = process.argv[2] ?? process.env.OPENFRONT_DIR ?? path.resolve(here, "../../OpenFrontIO");
const src = fs.readFileSync(path.join(upstream, "src/core/game/NationCreation.ts"), "utf8");

function block(re) {
  const m = re.exec(src);
  if (!m) throw new Error("block not found: " + re);
  return m[1];
}
const templatesSrc = block(/const NAME_TEMPLATES: NameTemplate\[\] = \[([\s\S]*?)\n\];/);
const templates = [...templatesSrc.matchAll(/\[([^\]]*)\]/g)].map((m) =>
  m[1].split(",").map((p) => p.trim()).filter(Boolean).map((p) => (p === "NOUN" ? "NOUN" : p === "PLURAL_NOUN" ? "PLURAL" : JSON.parse(p))),
);
const nouns = JSON.parse("[" + block(/const NOUNS = \[([\s\S]*?)\];/).replace(/,\s*$/, "") + "]");
const oes = JSON.parse("[" + block(/const O_TO_OES = new Set\(\[([\s\S]*?)\]\);/) + "]");
const special = [...block(/const SPECIAL_PLURALS = new Map\(\[([\s\S]*?)\]\);/).matchAll(/\["([^"]+)", "([^"]+)"\]/g)].map((m) => [m[1], m[2]]);

const lua = (v) => (v === "NOUN" ? "NOUN" : v === "PLURAL" ? "PLURAL" : JSON.stringify(v));
const out = `-- AUTO-GENERATED by tools/gen-nation-creation.mjs from upstream
-- src/core/game/NationCreation.ts. Do not edit by hand.
--
-- createNationsForGame: which nations take part. "disabled" -> none; a
-- number -> that many (manifest, then additionalNations, then generated
-- names); "default" -> public compact maps use 25 % of the manifest nations
-- (min 1), everything else all of them.

local GameTypes = require(script.Parent.GameTypes)

local PlayerType = GameTypes.PlayerType

local NOUN, PLURAL = {}, {} -- template markers

local NAME_TEMPLATES = {
${templates.map((t) => `\t{ ${t.map(lua).join(", ")} },`).join("\n")}
}

local NOUNS = { ${nouns.map((n) => JSON.stringify(n)).join(", ")} }

local O_TO_OES = { ${oes.map((n) => `[${JSON.stringify(n)}] = true`).join(", ")} }

local SPECIAL_PLURALS = { ${special.map(([a, b]) => `[${JSON.stringify(a)}] = ${JSON.stringify(b)}`).join(", ")} }

local function endsWith(s: string, suffix: string): boolean
	return string.sub(s, -#suffix) == suffix
end

local function pluralize(noun: string): string
	if SPECIAL_PLURALS[noun] then
		return SPECIAL_PLURALS[noun]
	end
	if endsWith(noun, "s") or endsWith(noun, "ch") or endsWith(noun, "sh") or endsWith(noun, "x") or endsWith(noun, "z") then
		return noun .. "es"
	end
	if endsWith(noun, "y") and not string.find("aeiou", string.sub(noun, -2, -2), 1, true) then
		return string.sub(noun, 1, -2) .. "ies"
	end
	if O_TO_OES[noun] then
		return noun .. "es"
	end
	return noun .. "s"
end

local function generateNationName(random): string
	local template = NAME_TEMPLATES[random:nextInt(0, #NAME_TEMPLATES) + 1]
	local noun = NOUNS[random:nextInt(0, #NOUNS) + 1]
	local parts = {}
	for _, part in template do
		if part == PLURAL then
			table.insert(parts, pluralize(noun))
		elseif part == NOUN then
			table.insert(parts, noun)
		else
			table.insert(parts, part)
		end
	end
	return table.concat(parts, " ")
end

local function generateUniqueNationName(random, used): string
	for _ = 1, 1000 do
		local name = generateNationName(random)
		if not used[name] then
			return name
		end
	end
	local counter = 1
	local base = generateNationName(random)
	while used[\`{base} {counter}\`] do
		counter += 1
	end
	return \`{base} {counter}\`
end

local function toNation(n, random)
	local cell = if n.coordinates ~= nil then { x = n.coordinates[1], y = n.coordinates[2] } else nil
	return GameTypes.Nation(cell, GameTypes.PlayerInfo(n.name, PlayerType.Nation, nil, random:nextID(), false, nil, {}, nil, n.flag))
end

local function slice(list, count: number)
	return table.move(list, 1, math.min(count, #list), 1, {})
end

local function createRandomNations(targetCount: number, manifestNations, additionalNations, random)
	local shuffled = random:shuffleArray(manifestNations)
	if targetCount <= #manifestNations then
		local out = {}
		for i, n in slice(shuffled, targetCount) do
			out[i] = toNation(n, random)
		end
		return out
	end
	local nations, used = {}, {}
	for _, n in shuffled do
		local nat = toNation(n, random)
		table.insert(nations, nat)
		used[nat.playerInfo.name] = true
	end
	local remaining = targetCount - #manifestNations
	if remaining > 0 and #additionalNations > 0 then
		local candidates = {}
		for _, n in additionalNations do
			if not used[n.name] then
				table.insert(candidates, n)
			end
		end
		local picked = slice(random:shuffleArray(candidates), remaining)
		for _, extra in picked do
			table.insert(nations, toNation(extra, random))
			used[extra.name] = true
		end
		remaining -= #picked
	end
	for _ = 1, remaining do
		local name = generateUniqueNationName(random, used)
		used[name] = true
		table.insert(nations, GameTypes.Nation(nil, GameTypes.PlayerInfo(name, PlayerType.Nation, nil, random:nextID())))
	end
	return nations
end

local NationCreation = {}

-- For compact maps, only 25 % of nations are used (minimum 1).
function NationCreation.getCompactMapNationCount(manifestCount: number, isCompact: boolean): number
	if manifestCount == 0 then
		return 0
	end
	if isCompact then
		return math.max(1, math.floor(manifestCount * 0.25))
	end
	return manifestCount
end

function NationCreation.createNationsForGame(config, manifestNations, additionalNations, numHumans: number, random)
	local gc = config
	local isCompact = gc.gameMapSize == GameTypes.GameMapSize.Compact
	local isHvN = gc.gameMode == GameTypes.GameMode.Team and gc.playerTeams == GameTypes.HumansVsNations
	local configNations = gc.nations
	if configNations == "disabled" then
		return {}
	end
	if type(configNations) == "number" then
		return createRandomNations(configNations, manifestNations, additionalNations, random)
	end
	if gc.gameType == GameTypes.GameType.Public then
		if isHvN then
			return createRandomNations(numHumans, manifestNations, additionalNations, random)
		end
		if isCompact then
			local count = NationCreation.getCompactMapNationCount(#manifestNations, true)
			local out = {}
			for i, n in slice(random:shuffleArray(manifestNations), count) do
				out[i] = toNation(n, random)
			end
			return out
		end
	end
	local out = {}
	for i, n in manifestNations do
		out[i] = toNation(n, random)
	end
	return out
end

return NationCreation
`;
fs.writeFileSync(path.resolve(here, "../src/server/Core/NationCreation.luau"), out);
console.log(`${templates.length} templates, ${nouns.length} nouns`);
